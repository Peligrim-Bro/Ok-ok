const {test,expect}=require('@playwright/test');
for(const lang of ['ru','en','th'])for(const theme of ['dark','light'])test(`owner soup recommendation ${lang} ${theme}`,async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.addInitScript(({lang,theme})=>{localStorage.setItem('pok-lang',lang);localStorage.setItem('pok-lang-set','1');localStorage.setItem('pok-theme',theme);},{lang,theme});
 await page.goto('/',{waitUntil:'domcontentloaded'});await page.locator('#installClose').click();
 const card=page.locator('.card[data-open="musselana-shabu"]');
 await expect(card).toHaveCount(1);
 await expect(card.locator('.flag')).toHaveText({ru:'✓ OK · Проверено',en:'✓ OK · Verified',th:'✓ OK · ตรวจสอบแล้ว'}[lang]);
 await expect(card).toContainText('80');await expect(card).toContainText('13:00');
 await expect(card.locator('.stars')).toHaveCount(0);
 await expect(card).toContainText({ru:'Примерный график',en:'Approximate hours',th:'เวลาโดยประมาณ'}[lang]);
 await card.scrollIntoViewIfNeeded();
 await expect.poll(()=>card.evaluate(n=>Number(getComputedStyle(n).opacity))).toBe(1);
 await expect.poll(()=>card.locator('img').evaluate(i=>i.complete&&i.naturalWidth>0)).toBe(true);
 await card.screenshot({path:`quality-reports/soup-card-${lang}-${theme}.png`});
 await card.click();
 await expect(page.locator('#sheet')).toHaveClass(/open/);
 await expect(page.locator('#sheet .owner-review')).toContainText({ru:'2 недели подряд',en:'two weeks',th:'สองสัปดาห์'}[lang]);
 await expect(page.locator('#sheet')).toContainText('VV6W+G8C');
 await expect(page.locator('#sheet .gallery img')).toHaveCount(5);
 await expect.poll(()=>page.locator('#sheet .gallery img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0))).toBe(true);
 await expect(page.locator('#sheet a.btn.map')).toHaveAttribute('href','https://www.google.com/maps/search/?api=1&query=7P42VV6W%2BG8C');
 await page.locator('#sheet').evaluate(n=>{n.scrollTop=n.scrollHeight});await expect(page.locator('#closeSheet')).toBeVisible();
 await page.screenshot({path:`quality-reports/soup-detail-${lang}-${theme}.png`});
 await page.locator('#closeSheet').click();await expect(page.locator('#sheet')).not.toHaveClass(/open/);
 await page.locator('[data-openmap]').click();
 const point=page.locator('[data-map-place="musselana-shabu"]');await expect(point).toBeVisible();await point.click();
 await expect(page.locator('.map-detail[data-place="musselana-shabu"]')).toContainText('80');
 await expect(page.locator('.map-detail-actions a').first()).toHaveAttribute('href',/destination=7P42VV6W%2BG8C/);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
