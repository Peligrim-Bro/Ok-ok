import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
execFileSync(process.execPath,['--test','tests/content-freshness.test.mjs'],{stdio:'inherit'});
const source=readFileSync('content-freshness.js','utf8');
const asset='assets/content-freshness-'+createHash('sha256').update(source).digest('hex').slice(0,16)+'.js';
writeFileSync('site/public/'+asset,source);
const path='site/public/index.html';
let html=readFileSync(path,'utf8');
const original='<p class="hint" style="margin:0 0 8px">${lang === "ru" ? "Проверено" : lang === "th" ? "ตรวจสอบแล้ว" : "Checked"} · ${CFG.newsVerifiedAt || ""}</p>';
assert(html.includes(original),'News review label anchor missing');
html=html.replace(original,"${window.OKOK_FRESHNESS?.html('news', CFG.newsVerifiedAt, lang) || `"+original+"`}");
const config='<script src="config.js?v=99"></script>';
assert(html.includes(config),'Freshness must load before first news render');
html=html.replace(config,'<script src="'+asset+'"></script>'+config);
html=html.replace('</head>','<style id="okok-freshness-style">.content-freshness{margin:0 0 8px;overflow-wrap:anywhere}.freshness-note{display:block;margin-top:5px;font-weight:700}.content-freshness[data-freshness-state="due"],.content-freshness[data-freshness-state="unknown"]{border-inline-start:3px solid var(--mint,#57efc3);padding-inline-start:10px}</style></head>');
writeFileSync(path,html);
const sw='site/public/sw.js',worker=readFileSync(sw,'utf8');
assert(worker.includes('const CORE = ['),'Offline cache anchor missing');
writeFileSync(sw,worker.replace('const CORE = [','const CORE = [\n  "'+asset+'",'));
await import('./audit-content-freshness.mjs');
